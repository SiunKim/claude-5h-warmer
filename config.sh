# 핑을 보낼 시각들 (24시간제, 로컬 시간). 공백으로 구분.
#   각 시각이 Claude "5시간 사용 창"을 하나 엽니다.
#   5시간 간격으로 두면 창이 끊기지 않고 이어집니다.
#     예) 아침형    "06:00 11:00 16:00"  → 06~21시 커버
#         늦게 시작  "09:00 14:00 19:00"
#         하루 한 번 "08:00"
#   ("6" 처럼 시만 적으면 06:00 으로 간주)
