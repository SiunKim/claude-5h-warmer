# 사용할 모델 (가벼울수록 쿼터 절약). 별칭 "haiku" 또는 정확한 모델 ID.
CM_MODEL="claude-haiku-4-5-20251001"

# 보낼 프롬프트 (짧을수록 좋음 — 목적은 '창 열기'일 뿐).
